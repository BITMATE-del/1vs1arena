import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createMoneyEngine} from './money-engine.mjs';
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE tron_wallets(user_id INTEGER PRIMARY KEY,balance_micro INTEGER NOT NULL CHECK(balance_micro>=0),updated INTEGER NOT NULL);CREATE TABLE matches(id INTEGER PRIMARY KEY,owner INTEGER NOT NULL,guest INTEGER NOT NULL,state TEXT NOT NULL,a INTEGER NOT NULL DEFAULT 0,b INTEGER NOT NULL DEFAULT 0);INSERT INTO tron_wallets VALUES(101,100000000,1),(102,100000000,1);INSERT INTO matches VALUES(1,101,102,'active',0,0),(2,101,102,'active',0,0),(3,101,102,'active',0,0),(4,101,102,'active',0,0),(5,101,102,'active',0,0),(6,101,102,'active',0,0)");
const money=createMoneyEngine(db,{now:()=>1900000000000});
const balance=id=>Number(money.balance(id));
assert.equal(money.deposit(1,'GA-AAA',101,102,10000000).ok,true);
assert.equal(balance(101),90000000);assert.equal(balance(102),90000000);
assert.equal(money.deposit(1,'GA-AAA',101,102,10000000).reused,true);
assert.equal(balance(101),90000000,'repeat reserve never withdraws again');
db.prepare("UPDATE matches SET state='finished',a=3,b=1 WHERE id=1").run();
assert.equal(money.reconcile().done,1);
assert.equal(balance(101),109400000,'winner gets 19.4 USDT with 10 each stake');
assert.equal(balance(102),90000000);
assert.equal(money.summary().fees,600000);
assert.equal(money.reconcile().done,0);
assert.equal(money.settle(db.prepare('SELECT * FROM matches WHERE id=1').get()).reused,true);
assert.equal(balance(101),109400000);
assert.equal(money.deposit(2,'GA-BBB',101,102,10000000).ok,true);
db.prepare("UPDATE matches SET state='finished',a=2,b=2 WHERE id=2").run();
assert.equal(money.settle(db.prepare('SELECT * FROM matches WHERE id=2').get()).decision,'refund');
assert.equal(balance(101),109400000);assert.equal(balance(102),90000000);
assert.equal(money.deposit(3,'GA-CCC',101,102,10000000).ok,true);
db.prepare("UPDATE matches SET state='cancelled',a=3,b=1 WHERE id=3").run();
assert.equal(money.reconcile().done,1);
assert.equal(balance(101),109400000);assert.equal(balance(102),90000000);
assert.equal(money.summary().fees,600000,'refunds do not pay platform fees');
assert.equal(money.deposit(4,'GA-DDD',101,102,90000000).ok,true);
assert.equal(balance(102),0);
const fail=money.deposit(5,'GA-EEE',101,102,1000000);
assert.equal(fail.ok,false);
assert.equal(balance(101),19400000,'failed second user debit rolls first user back');
assert.equal(balance(102),0);
db.prepare("UPDATE matches SET state='cancelled' WHERE id=4").run();
assert.equal(money.reconcile().done,1);
assert.equal(balance(101),109400000);assert.equal(balance(102),90000000);
assert.equal(money.deposit(6,'GA-FFF',101,102,10000000).ok,true);
db.prepare("UPDATE matches SET state='finished',a=0,b=2 WHERE id=6").run();
assert.equal(money.reconcile().done,1);
assert.equal(balance(101),99400000);
assert.equal(balance(102),99400000);
assert.equal(money.summary().fees,1200000);
assert.equal(db.prepare('SELECT COUNT(*) n FROM money_settlements').get().n,5);
assert.throws(()=>db.prepare('DELETE FROM money_ledger').run(),/IMMUTABLE/);
assert.throws(()=>db.prepare("UPDATE money_ledger SET delta_micro=0").run(),/IMMUTABLE/);
const holds=db.prepare("SELECT COUNT(*) n FROM money_ledger WHERE kind='stake_hold'").get().n;
assert.equal(holds,10);
assert.equal(money.summary().open,0);
assert.equal(BigInt(balance(101))+BigInt(balance(102))+BigInt(money.summary().fees),200000000n,'all internal USDT conserved across escrow+fees');
console.log('GLORY ARENA real internal USDT settlement tests PASS: atomic stakes, 3% fee, winner payout, draw/stop refund, rematch, insufficient balance rollback, dedupe, immutable ledger, total conservation');
