import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createSettlementJournal,classifyMatch,refundPreview,matchSettlementPreview} from './settlement-journal.mjs';
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE matches(id INTEGER PRIMARY KEY,chat INTEGER,owner INTEGER,guest INTEGER,game TEXT,mode TEXT,rounds INTEGER,state TEXT,a INTEGER,b INTEGER);INSERT INTO matches VALUES(1,-100,101,102,'🎲','wins',3,'finished',2,0);INSERT INTO matches VALUES(8,-108,101,102,'🎲','wins',3,'active',0,0)");
const journal=createSettlementJournal(db,{now:()=>1900000000000});
assert.equal(journal.summary().cutoff,8,'historical cutoff includes preexisting active games');
const insert=(id,state,a,b)=>db.prepare('INSERT INTO matches VALUES(?,?,?,?,?,?,?,?,?,?)').run(id,-100,101,102,'🎲','wins',3,state,a,b);
insert(2,'finished',3,2);
insert(3,'finished',2,2);
insert(4,'cancelled',2,1);
insert(5,'cancelled',0,0);
insert(6,'active',0,0);
assert.equal(journal.reconcile().recorded,4);
assert.equal(journal.reconcile().recorded,0,'replayed reconciliation creates no extra decisions');
assert.equal(journal.summary().total,4);
db.prepare("UPDATE matches SET state='finished',a=2,b=0 WHERE id=8").run();
assert.equal(journal.reconcile().recorded,1,'preexisting active match must be audited on completion');
assert.equal(journal.summary().total,5);
assert.equal(journal.summary().winners,2);
assert.equal(journal.summary().refunds,3);
assert.equal(journal.record(db.prepare('SELECT * FROM matches WHERE id=2').get()).status,'already_recorded');
assert.equal(journal.record(db.prepare('SELECT * FROM matches WHERE id=1').get()).status,'historical_skipped');
const entries=journal.entries();
assert(entries.every(journal.verify),'all records preserve integrity');
const decisive=entries.find(e=>e.match_id===2);
assert.equal(decisive.fee_bps,300);
assert.equal(decisive.winner_id,101);
assert.equal(decisive.execution_state,'preview_only');
for(const i of [3,4,5]){const v=entries.find(x=>x.match_id===i);assert.equal(v.decision,'refund_both');assert.equal(v.fee_bps,0);assert.equal(v.winner_id,null);}
assert.equal(classifyMatch({id:6,state:'active'}),null);
const future=matchSettlementPreview({id:10,state:'finished',owner:101,guest:102,a:1,b:0},100000000n,100000000n);
assert.equal(future.winnerPayout,194000000n);
assert.equal(future.fee,6000000n);
const refund=refundPreview(100000000n,250000000n);
assert.equal(refund.refundA,100000000n);
assert.equal(refund.refundB,250000000n);
assert.equal(refund.fee,0n);
assert.throws(()=>db.prepare('UPDATE match_settlement_decisions SET fee_bps=400 WHERE match_id=2').run(),/IMMUTABLE/);
assert.throws(()=>db.prepare('DELETE FROM match_settlement_decisions WHERE match_id=2').run(),/IMMUTABLE/);
db.prepare("UPDATE matches SET a=0,b=10 WHERE id=2").run();
assert.equal(journal.reconcile().recorded,0,'underlying match corrections do not silently rewrite the original settlement audit');
const second=createSettlementJournal(db,{now:()=>1900000000001});
assert.equal(second.summary().cutoff,8,'restart keeps initial historical cutoff');
assert.equal(second.reconcile().recorded,0);
console.log('GLORY ARENA settlement journal PASS: 3% winner calculation, full refunds, fee-free draws/stops, idempotency, history cutoff, immutable verified audit');
