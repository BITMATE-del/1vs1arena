import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createMatchWatch} from './match-watch.mjs';

const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE matches(id INTEGER PRIMARY KEY,chat INTEGER,owner INTEGER,guest INTEGER,game TEXT,mode TEXT,rounds INTEGER,state TEXT,turn INTEGER,round INTEGER,a INTEGER,b INTEGER);CREATE TABLE arena_users(id INTEGER PRIMARY KEY,name TEXT,username TEXT);CREATE TABLE match_requests(code TEXT PRIMARY KEY,match_id INTEGER);CREATE TABLE match_continue_votes(code TEXT PRIMARY KEY,state TEXT);CREATE TABLE generated_rooms(code TEXT PRIMARY KEY,status TEXT)");
db.prepare("INSERT INTO arena_users VALUES(?,?,?)").run(11,'선수 A','player_a');
db.prepare("INSERT INTO arena_users VALUES(?,?,?)").run(12,'선수 B','player_b');
db.prepare("INSERT INTO matches VALUES(?,?,?,?,?,?,?,?,?,?,?,?)").run(5,-1001,11,12,'🎲','wins',3,'active',11,1,0,0);
db.prepare("INSERT INTO match_requests VALUES(?,?)").run('GA-AAAABBBB',5);
let t=1000000;
const sent=[],expired=[],clock=()=>t,watch=createMatchWatch(db,(chat,message)=>sent.push({chat,message}),{now:clock,getConfig:key=>key==='turn_warn_minutes'?'3':'20',onTimeout:id=>{expired.push(id);db.prepare("UPDATE matches SET state='cancelled' WHERE id=?").run(id);}});
assert.equal(watch.sync(),1);
assert.equal(watch.tick().warnings,0);
t+=3*60000+1;assert.equal(watch.tick().warnings,1);
assert.equal(watch.tick().warnings,0,'no repeated warning');
assert.equal(sent.length,2,'group and player private reminder exactly once');
assert.equal(watch.issueSummary().incidents,1);
assert.equal(watch.issueSummary().warnings,1);
assert.equal(watch.tick().expired,0);
t+=17*60000;assert.equal(watch.tick().expired,1);
assert.deepEqual(expired,[5]);
assert.equal(watch.tick().expired,0,'timeout idempotent');
assert.equal(db.prepare('SELECT state FROM matches WHERE id=5').get().state,'cancelled');
watch.sync();assert.equal(db.prepare('SELECT COUNT(*) n FROM match_turn_watch').get().n,0);
db.prepare("UPDATE matches SET state='active',turn=12 WHERE id=5").run();
assert(watch.arm(5),'restarting a new turn arms fresh timer');
assert.equal(db.prepare("SELECT COUNT(*) n FROM arena_incidents WHERE state='open'").get().n,0);
const first=db.prepare("SELECT turn_started FROM match_turn_watch WHERE match_id=5").get().turn_started;
t+=60000;watch.sync();assert.equal(db.prepare('SELECT turn_started FROM match_turn_watch WHERE match_id=5').get().turn_started,first,'restart recovery preserves elapsed time');
db.prepare("UPDATE matches SET turn=11 WHERE id=5").run();watch.sync();assert.equal(db.prepare('SELECT turn_player FROM match_turn_watch WHERE match_id=5').get().turn_player,11);
assert.equal(db.prepare('SELECT turn_started FROM match_turn_watch WHERE match_id=5').get().turn_started,t);
db.prepare("UPDATE matches SET state='finished' WHERE id=5").run();watch.touch(5);
assert.equal(db.prepare('SELECT COUNT(*) n FROM match_turn_watch').get().n,0,'completed games are never timed out');
assert.equal(watch.tick().expired,0);
console.log('GLORY ARENA watchdog tests PASS: warning, timeout, restart, turn recovery, dedupe, historic safety');
