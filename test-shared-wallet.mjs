import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createHash} from 'node:crypto';
import {createTronDeposits,USDT_TRON,usdtDisplay} from './tron-deposits.mjs';
import {createSharedWallet,parseUsdt} from './shared-wallet.mjs';
const alphabet='123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz';
function address(seed){const data=Buffer.concat([Buffer.from([65]),Buffer.alloc(20,seed)]),sha=x=>createHash('sha256').update(x).digest(),bytes=Buffer.concat([data,sha(sha(data)).subarray(0,4)]);let n=BigInt('0x'+bytes.toString('hex')),o='';while(n){o=alphabet[Number(n%58n)]+o;n/=58n;}return o;}
assert.equal(String(parseUsdt('10.123456')),'10123456');
assert.equal(parseUsdt('10.1234567'),null);
assert.equal(parseUsdt('-10'),null);
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE arena_users(id INTEGER PRIMARY KEY,name TEXT);INSERT INTO arena_users VALUES(11,'A'),(12,'B')");
let t=1900000000000,seen=[],enabled=true,credits=[],calls=0,solid=true;
const treasury=address(7);
const fetcher=async(url,opts)=>{
 calls++;
 if(url.includes('/transactions/trc20'))return {ok:true,json:async()=>({success:true,data:seen,meta:{}})};
 if(url.includes('/walletsolidity/gettransactioninfobyid'))return {ok:true,json:async()=>({id:JSON.parse(opts.body).value,receipt:{result:solid?'SUCCESS':'FAILED'}})};
 throw Error('unexpected request');
};
const send=(user,text)=>credits.push({user,text});
createTronDeposits(db,send,{enabled:()=>false,apiKey:'test'});
const w=createSharedWallet(db,send,{apiKey:'test',enabled:()=>enabled,now:()=>t,fetcher});
assert(w.setAddress(treasury));
assert.equal(w.treasury(),treasury);
const invoice1=w.invoice(11,'10'),invoice2=w.invoice(12,'10');
assert(invoice1.ok&&invoice2.ok);
assert.notEqual(invoice1.invoice.amount_micro,invoice2.invoice.amount_micro,'shared invoices must be distinguishable');
assert.equal(w.invoice(11,'10').invoice.id,invoice1.invoice.id,'pending invoice reused');
const tx1='a'.repeat(64),tx2='b'.repeat(64);
const transfer=(id,amount)=>({transaction_id:id,from:address(9),to:treasury,block_timestamp:t+1000,value:String(amount),token_info:{address:USDT_TRON,decimals:6}});
seen=[transfer(tx1,invoice1.invoice.amount_micro),transfer(tx2,invoice2.invoice.amount_micro)];
assert.equal((await w.poll()).credited,2,'separate same-wallet transfers auto-credited using exact amount');
assert.equal(credits.length,2);
assert.equal(db.prepare('SELECT COUNT(*) n FROM tron_deposits').get().n,2,'deposits persisted in existing unified ledger');
assert.equal(db.prepare('SELECT balance_micro FROM tron_wallets WHERE user_id=11').get().balance_micro,invoice1.invoice.amount_micro);
assert.equal((await w.poll()).credited,0,'repeat scan cannot credit twice');
assert.equal(credits.length,2);
const wd=w.requestWithdrawal(11,address(4),'4');
assert(wd.ok,'balance held for withdrawal');
const after=BigInt(w.invoice(11,'10').invoice.amount_micro);
assert(w.cancelWithdrawal(wd.id));
assert.equal(w.cancelWithdrawal(wd.id),false,'cancel idempotent');
assert.equal(String(db.prepare('SELECT balance_micro FROM tron_wallets WHERE user_id=11').get().balance_micro),String(after));
assert.equal(w.requestWithdrawal(11,'bad_address','3').ok,false);
assert.equal(w.requestWithdrawal(11,address(4),'999').ok,false);
const noMatch='c'.repeat(64);
seen=[transfer(noMatch,'3456789')];
assert.equal((await w.poll()).credited,0);
assert.equal(w.status().unmatched,1);
solid=false;
const notSolid='d'.repeat(64);
const invoice3=w.invoice(11,'3');
seen=[transfer(notSolid,invoice3.invoice.amount_micro)];
assert.equal((await w.poll()).credited,0,'failed transaction cannot credit');
solid=true;enabled=false;
const before=calls;
assert.equal((await w.poll()).active,false);
assert.equal(calls,before);
assert.equal(w.invoice(12,'50').ok,false);
assert.equal(w.requestWithdrawal(12,address(4),'1').ok,true,'user can request withdrawal from credited funds without signing');
console.log('GLORY ARENA shared treasury tests PASS: one address, distinct invoices, confirmed auto-credit, replay, unmatched, held withdrawals, cancellation, disabled switch');
