import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createMatchFlow} from './match-flow.mjs';
import {createMoneyEngine} from './money-engine.mjs';
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE arena_users(id INTEGER PRIMARY KEY,name TEXT,username TEXT,blocked INTEGER DEFAULT 0);CREATE TABLE matches(id INTEGER PRIMARY KEY,chat INTEGER,owner INTEGER,guest INTEGER,game TEXT,mode TEXT,rounds INTEGER,state TEXT,turn INTEGER,round INTEGER DEFAULT 1,a INTEGER DEFAULT 0,b INTEGER DEFAULT 0);CREATE TABLE generated_rooms(code TEXT PRIMARY KEY,chat INTEGER,status TEXT,link TEXT,link_guest TEXT);CREATE TABLE tron_wallets(user_id INTEGER PRIMARY KEY,balance_micro INTEGER NOT NULL DEFAULT 0 CHECK(balance_micro>=0),updated INTEGER NOT NULL);INSERT INTO arena_users VALUES(101,'A','playeralpha',0),(102,'B','playerbravo',0);INSERT INTO tron_wallets VALUES(101,20000000,0),(102,20000000,0)");
const messages=[],rooms=new Map(),events=new Map();const send=(user,message,keyboard)=>messages.push({user,message,keyboard});
const room={connected:()=>true,requestPair:(data,onReady,onFailed)=>{
 const code='R-'+data.code,chat=-1004444;
 rooms.set(code,{code,chat,status:'ready',link:'https://t.me/+x',link_guest:'https://t.me/+y'});
 db.prepare('INSERT INTO generated_rooms VALUES(?,?,?,?,?)').run(code,chat,'ready','https://t.me/+x','https://t.me/+y');
 events.set(code,{onReady,onFailed});return code;},
 getByCode:code=>rooms.get(code),finish:code=>{rooms.get(code).status='finished'},reopen:code=>{rooms.get(code).status='ready'},close:async code=>{rooms.get(code).status='closed';return true}};
const money=createMoneyEngine(db,{now:()=>1900000000000});
const flow=createMatchFlow(db,send,room,{'🎲':['다이스',6]},{wins:'선승제'},[1,3],{gameEnabled:()=>true,money,paidMatchesEnabled:()=>true,onMatchEnd:id=>money.settle(db.prepare('SELECT * FROM matches WHERE id=?').get(id))});
const a=(user,chat,...p)=>{assert.equal(flow.onCallback(user,chat,['mf',...p]),true)};
const latest=()=>db.prepare('SELECT * FROM match_requests ORDER BY rowid DESC LIMIT 1').get();
function start(){
 a(101,101,'public');const row=latest();
 a(101,101,'game',row.code,'🎲');
 a(101,101,'mode',row.code,'wins');
 a(101,101,'round',row.code,'1');
 assert.equal(flow.onText(101,'10'),true);
 assert.equal(latest().stake_micro,10000000);
 a(101,101,'submit',row.code);
 a(102,102,'join',row.code);
 a(101,101,'accept',row.code);
 events.get('R-'+row.code).onReady(row.code,{chat:-1004444,code:'R-'+row.code,linkOwner:'https://t.me/+x',linkGuest:'https://t.me/+y'});
 return row.code;
}
const code=start();
assert.equal(latest().status,'room_ready');
a(101,-1004444,'notice',code);a(102,-1004444,'notice',code);
a(101,-1004444,'ready',code);
assert.equal(Number(money.balance(101)),20000000,'do not charge first player before both consent');
a(102,-1004444,'ready',code);
assert.equal(latest().status,'playing');
assert.equal(Number(money.balance(101)),10000000);
assert.equal(Number(money.balance(102)),10000000);
const match=latest().match_id;
db.prepare("UPDATE matches SET state='finished',a=1,b=0 WHERE id=?").run(match);
flow.finished(-1004444);
assert.equal(Number(money.balance(101)),29400000);
assert.equal(Number(money.balance(102)),10000000);
assert.equal(money.summary().fees,600000);
a(101,-1004444,'again',code,'yes');
a(102,-1004444,'again',code,'yes');
assert.equal(latest().status,'playing');
const rematch=latest().match_id;
assert.notEqual(rematch,match);
assert.equal(Number(money.balance(101)),19400000);
assert.equal(Number(money.balance(102)),0);
db.prepare("UPDATE matches SET state='cancelled' WHERE id=?").run(rematch);
const refund=money.settle(db.prepare('SELECT * FROM matches WHERE id=?').get(rematch));
assert.equal(refund.decision,'refund');
assert.equal(Number(money.balance(101)),29400000);
assert.equal(Number(money.balance(102)),10000000);
assert.equal(money.summary().fees,600000);
assert.equal(money.reconcile().done,0);
console.log('GLORY ARENA paid match integration PASS: stake choice, both-ready escrow, winner 1.94x, next-game re-escrow, full cancellation refund');
