import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { createMatchBoard } from './match-board.mjs';

const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE arena_users(id INTEGER PRIMARY KEY,name TEXT,username TEXT);CREATE TABLE matches(id INTEGER PRIMARY KEY,chat INTEGER,owner INTEGER,guest INTEGER,game TEXT,mode TEXT,rounds INTEGER,state TEXT,turn INTEGER,round INTEGER,a INTEGER,b INTEGER);CREATE TABLE rolls(chat INTEGER,message INTEGER,match INTEGER,round INTEGER,player INTEGER,value INTEGER);CREATE TABLE match_requests(code TEXT,match_id INTEGER)");
db.prepare("INSERT INTO arena_users(id,name,username) VALUES(?,?,?)").run(1,'천사','angel_one');
db.prepare("INSERT INTO arena_users(id,name,username) VALUES(?,?,?)").run(2,'도전자','challenger_two');
db.prepare("INSERT INTO matches VALUES(?,?,?,?,?,?,?,?,?,?,?,?)").run(10,-100123,1,2,'🎲','total',3,'active',1,1,0,0);
db.prepare("INSERT INTO match_requests VALUES(?,?)").run('GA-TEST123',10);
const sent=[],queued=[],board=createMatchBoard(db,(method,p)=>queued.push({method,p}));
const tg=async(method,payload)=>{sent.push({method,payload});if(method==='sendMessage')return{message_id:99};return true;};
const get=()=>db.prepare('SELECT * FROM matches WHERE id=10').get();
let first=board.render(get());
assert(first.text.includes('현재 차례: @angel_one'));
assert(first.text.includes('GA-TEST123'));
assert(first.reply_markup.inline_keyboard.flat().some(x=>x.callback_data==='admincall'),'game board shows admin summon');
assert(!first.reply_markup.inline_keyboard.flat().some(x=>/dice|roll/i.test(x.callback_data||'')),'bot does not roll on behalf of player');
assert(first.text.includes('직접 보내주세요'),'board asks the player to send their own dice');
board.queueMatch(10);assert.equal(queued[0].method,'arenaBoardSync');
await board.sync(queued.shift().p,tg);
assert.deepEqual(sent.map(x=>x.method),['sendMessage','pinChatMessage','sendMessage']);
assert.equal(sent.at(-1).payload.reply_markup.keyboard[0][0].text,'🎲','Telegram reply keyboard sends from player account');
db.prepare("INSERT INTO rolls VALUES(?,?,?,?,?,?)").run(-100123,100,10,1,1,4);
db.prepare("UPDATE matches SET turn=2 WHERE id=10").run();
await board.sync({chat_id:-100123,match_id:10},tg);
assert.equal(sent.at(-1).method,'editMessageText','update same status board');
assert(sent.at(-1).payload.text.includes('현재 차례: @challenger_two'));
assert(sent.at(-1).payload.text.includes('1라운드  4 : –'));
assert(sent.at(-1).payload.reply_markup.inline_keyboard.flat().some(x=>x.callback_data==='admincall'),'admin summon stays on board');
assert(!sent.at(-1).payload.reply_markup.inline_keyboard.flat().some(x=>/dice|roll/i.test(x.callback_data||'')),'never instruct bot to roll dice');
db.prepare("INSERT INTO rolls VALUES(?,?,?,?,?,?)").run(-100123,101,10,1,2,5);
db.prepare("UPDATE matches SET a=4,b=5,round=2,turn=1").run();
await board.sync({chat_id:-100123,match_id:10},tg);
assert(sent.at(-1).payload.text.includes('A 4  :  5 B'));
assert(sent.at(-1).payload.text.includes('1라운드  4 : 5'));
db.prepare("UPDATE matches SET state='finished',a=9,b=11,turn=NULL").run();
await board.sync({chat_id:-100123,match_id:10},tg);
assert(sent.at(-1).payload.text.includes('승리: @challenger_two'));
assert(sent.at(-1).payload.reply_markup.inline_keyboard.flat().some(x=>x.callback_data==='admincall'));

db.prepare("UPDATE matches SET state='cancelled' WHERE id=10").run();
await board.sync({chat_id:-100123,match_id:10},tg);
assert(sent.at(-1).payload.text.includes('경기 중도 종료'),'stopped match shows terminated status');
assert.deepEqual(sent.at(-1).payload.reply_markup.inline_keyboard.flat().map(x=>x.callback_data),['admincall'],'stopped match retains only support call, no game actions');
console.log('GLORY ARENA pinned match board tests PASS',sent.length,'Telegram calls');
